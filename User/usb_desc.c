void USB_Display_SetSerial(const char *serial)
{
    uint8_t i;
    for (i = 0; i < 8; ++i) {
        uint8_t ch = ' ';
        if ((serial != 0) && (serial[i] != 0)) {
            ch = (uint8_t)serial[i];
        } else {
            serial = 0;
        }
        MySerNumInfo[2U + (i * 2U)] = ch;
    }
}
